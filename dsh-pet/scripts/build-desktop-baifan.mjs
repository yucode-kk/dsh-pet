#!/usr/bin/env node
/**
 * 把「吃白饭」桌面版（src/client/baifan/desktop.ts）构建成桌宠 Helper 的经典 script：
 * runtime/electron-helper/baifan.js，挂到全局 window.PetBaifan。
 *
 * 为什么单独产一份：Helper 页面从 file:// 加载，Chromium 对 file:// 的 ES module 有 CORS 限制，
 * 只能走经典 script；而网页端的吃白饭又依赖 DSH 的 shell.overlay 与宿主接口，进不了这个窗口。
 * 这一份只包演出与米饭层，素材与几何逻辑直接复用网页端源码，不复制实现。
 * 只产这一份构建产物，不做类型检查；由 npm run build:desktop-baifan 调用。
 * @module dsh-pet/scripts/build-desktop-baifan
 */
import { rolldown } from 'rolldown';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'runtime', 'electron-helper', 'baifan.js');

try {
  const bundle = await rolldown({
    input: join(ROOT, 'src', 'client', 'baifan', 'desktop.ts'),
    platform: 'browser',
  });
  await bundle.write({
    format: 'iife',
    name: 'PetBaifanModule',
    file: OUT,
    // 产物是经典脚本：把工厂挂到 window，菜单与事件侧只认 window.PetBaifan。
    footer: 'window.PetBaifan = PetBaifanModule.mountDesktopBaifan();',
    banner: [
      '/**',
      ' * @generated by `npm run build:desktop-baifan`（scripts/build-desktop-baifan.mjs），请勿手改。',
      ' * 源文件：src/client/baifan/desktop.ts（复用 scene/geometry/constants/assets）。',
      ' */',
    ].join('\n'),
  });
  console.log('[build-desktop-baifan] ✓ runtime/electron-helper/baifan.js (window.PetBaifan)');
} catch (error) {
  console.error('[build-desktop-baifan] build failed:', error);
  process.exit(1);
}